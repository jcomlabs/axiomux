import { existsSync, lstatSync, mkdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { parseDocument } from "yaml";
import { getPaths } from "../config.js";
import { SecretVault } from "../security/secret-vault.js";
import { secureStateDirectory, writePrivateFileAtomic } from "../security/state.js";
import type { ModelInfo } from "../types.js";

const PROVIDER_ID = "neuralwatt";
const SECRET_ENV = "NEURALWATT_API_KEY";
const BASE_URL = "https://api.neuralwatt.com/v1";
const PORTAL_URL = "https://portal.neuralwatt.com/";
const MAX_RESPONSE_BYTES = 2 * 1024 * 1024;
const MAX_MODEL_CONFIG_BYTES = 4 * 1024 * 1024;
const GENERATED_CONFIG_MARKER = "# Generated by Axiomux.";
const LEGACY_GENERATED_CONFIG_MARKERS = ["# Generated by RelayLoom.", "# Generated by SUPERAI."];

export type NeuralwattCredentialState = "available" | "not_configured" | "missing" | "unreadable";

export interface NeuralwattStatus {
  id: "neuralwatt";
  name: string;
  available: true;
  authenticated: boolean;
  credentialState: NeuralwattCredentialState;
  configuredModels: number;
  portalUrl: string;
  error?: string;
}

export interface NeuralwattLoginResult {
  models: ModelInfo[];
  modelConfigPath: string;
}

interface NeuralwattModel extends ModelInfo {
  cost: { input: number; output: number; cacheRead: number; cacheWrite: number };
  maxTokens: number;
}

export class NeuralwattProvider {
  private readonly paths;
  private readonly vault: SecretVault;

  constructor(
    root: string,
    private readonly fetchImpl: typeof fetch = globalThis.fetch,
    vault?: SecretVault,
  ) {
    this.paths = getPaths(root);
    this.vault = vault ?? new SecretVault(this.paths.stateDir);
  }

  status(): NeuralwattStatus {
    const credential = this.resolveCredential();
    const configState = this.modelConfigState();
    const error = credential.key || configState === "absent" || configState === "other" ? undefined : (credential.error ?? missingCredentialError());
    return {
      id: PROVIDER_ID,
      name: "Neuralwatt Cloud",
      available: true,
      authenticated: Boolean(credential.key),
      credentialState: credential.key
        ? "available"
        : configState === "absent" || configState === "other"
          ? "not_configured"
          : credential.error
            ? "unreadable"
            : "missing",
      configuredModels: this.configuredModels().length,
      portalUrl: PORTAL_URL,
      ...(error ? { error } : {}),
    };
  }

  /** Read the credential-free catalog without exposing the key to a discovery child. */
  configuredModels(): ModelInfo[] {
    if (this.modelConfigState() !== "managed") return [];
    try {
      const document = parseDocument(readBoundedModelConfig(this.modelConfigPath), { strict: true, uniqueKeys: true, prettyErrors: false });
      if (document.errors.length || document.warnings.length) return [];
      const root = objectValue(document.toJS({ maxAliasCount: 0 }));
      const providers = objectValue(root.providers);
      const provider = objectValue(providers.neuralwatt);
      if (!Array.isArray(provider.models)) return [];
      const models: ModelInfo[] = [];
      for (const entry of provider.models.slice(0, 500)) {
        const value = objectValue(entry);
        const id = typeof value.id === "string" ? value.id.trim() : "";
        if (!id || id.length > 220 || /[\u0000-\u001f\u007f]/u.test(id)) continue;
        const name = typeof value.name === "string" && value.name.trim() ? value.name.trim().slice(0, 180) : id;
        const input = Array.isArray(value.input)
          ? (value.input.filter((item) => item === "text" || item === "image").slice(0, 2) as Array<"text" | "image">)
          : ["text" as const];
        models.push({
          provider: PROVIDER_ID,
          id,
          selector: `${PROVIDER_ID}/${id}`,
          name,
          contextWindow: positiveNumber(value.contextWindow, 131_072, 2_000_000),
          reasoning: value.reasoning === true,
          input: input.length ? input : ["text"],
        });
      }
      return models;
    } catch {
      return [];
    }
  }

  /**
   * Resolve the Neuralwatt secret only for a child that will execute a
   * Neuralwatt model.  Catalog/login children and other providers must never
   * inherit this credential.
   */
  runtimeEnvironmentForModel(modelSelector: string): NodeJS.ProcessEnv {
    if (modelSelector.split("/", 1)[0]?.toLocaleLowerCase() !== PROVIDER_ID) return {};
    const credential = this.resolveCredential();
    if (credential.key) return { [SECRET_ENV]: credential.key };
    const configState = this.modelConfigState();
    if (configState === "managed" || configState === "unreadable") {
      throw new Error(credential.error ?? missingCredentialError());
    }
    return {};
  }

  async login(apiKey: string): Promise<NeuralwattLoginResult> {
    const key = apiKey.trim();
    if (!key || key.length > 4096 || /[\u0000-\u001f\u007f]/.test(key)) throw new Error("A valid Neuralwatt API key is required");
    const priorConfig = this.modelConfigState();
    if (priorConfig === "other" || priorConfig === "unreadable") {
      throw new Error(`Refusing to overwrite existing OMP models.yml (${priorConfig}); move or merge it explicitly before Neuralwatt login`);
    }
    await this.requestJson(`${BASE_URL}/quota`, key);
    const catalog = await this.requestJson(`${BASE_URL}/models`, key);
    const models = parseModels(catalog);
    if (!models.length) throw new Error("Neuralwatt returned no usable models; the credential was not stored");
    mkdirSync(this.paths.ompAgentDir, { recursive: true });
    const directorySecurity = secureStateDirectory(this.paths.ompAgentDir);
    if (!directorySecurity.hardened) throw new Error(`Neuralwatt was validated, but its model directory could not be secured: ${directorySecurity.detail}`);
    writePrivateFileAtomic(this.modelConfigPath, renderModelsYaml(models));
    this.vault.set(PROVIDER_ID, key);
    return { models, modelConfigPath: this.modelConfigPath };
  }

  /** Remove only the encrypted credential; the credential-free model catalog remains reusable. */
  logout(): boolean {
    return this.vault.delete(PROVIDER_ID);
  }

  private get modelConfigPath(): string {
    return join(this.paths.ompAgentDir, "models.yml");
  }

  private resolveCredential(): { key?: string; error?: string } {
    const environment = process.env[SECRET_ENV]?.trim();
    if (environment) return { key: environment };
    try {
      const key = this.vault.get(PROVIDER_ID);
      return key ? { key } : {};
    } catch {
      return { error: unreadableCredentialError() };
    }
  }

  private modelConfigState(): "absent" | "managed" | "other" | "unreadable" {
    if (!existsSync(this.modelConfigPath)) return "absent";
    try {
      const content = readBoundedModelConfig(this.modelConfigPath);
      return [GENERATED_CONFIG_MARKER, ...LEGACY_GENERATED_CONFIG_MARKERS].some((marker) => content.startsWith(`${marker} Contains no credential;`))
        ? "managed"
        : "other";
    } catch {
      return "unreadable";
    }
  }

  private async requestJson(url: string, key: string): Promise<unknown> {
    const response = await this.fetchImpl(url, {
      redirect: "error",
      headers: { Authorization: `Bearer ${key}`, Accept: "application/json" },
      signal: AbortSignal.timeout(20_000),
    });
    if (response.status === 401 || response.status === 403) throw new Error("Neuralwatt rejected the API key");
    if (!response.ok) throw new Error(`Neuralwatt request failed (HTTP ${response.status})`);
    const declared = Number(response.headers.get("content-length") ?? 0);
    if (declared > MAX_RESPONSE_BYTES) throw new Error("Neuralwatt response exceeded the safe size limit");
    const bytes = await readBoundedResponse(response, MAX_RESPONSE_BYTES);
    try {
      return JSON.parse(new TextDecoder().decode(bytes)) as unknown;
    } catch {
      throw new Error("Neuralwatt returned invalid JSON");
    }
  }
}

async function readBoundedResponse(response: Response, limit: number): Promise<Uint8Array> {
  if (!response.body) return new Uint8Array();
  const reader = response.body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!value) continue;
      total += value.byteLength;
      if (total > limit) {
        await reader.cancel("response size limit exceeded").catch(() => undefined);
        throw new Error("Neuralwatt response exceeded the safe size limit");
      }
      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }
  const result = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    result.set(chunk, offset);
    offset += chunk.byteLength;
  }
  return result;
}

function parseModels(body: unknown): NeuralwattModel[] {
  if (!body || typeof body !== "object" || !Array.isArray((body as { data?: unknown }).data)) throw new Error("Neuralwatt returned an invalid model catalog");
  const models: NeuralwattModel[] = [];
  for (const entry of (body as { data: unknown[] }).data.slice(0, 500)) {
    if (!entry || typeof entry !== "object") continue;
    const raw = entry as Record<string, unknown>;
    const id = typeof raw.id === "string" ? raw.id.trim() : "";
    if (!id || id.length > 220 || /[\u0000-\u001f\u007f]/.test(id)) continue;
    const metadata = objectValue(raw.metadata);
    if (metadata.deprecated === true) continue;
    const capabilities = objectValue(metadata.capabilities);
    const limits = objectValue(metadata.limits);
    const pricing = objectValue(metadata.pricing);
    const display = typeof metadata.display_name === "string" && metadata.display_name.trim() ? metadata.display_name.trim().slice(0, 180) : id;
    const contextWindow = positiveNumber(limits.max_context_length ?? raw.max_model_len, 131_072, 2_000_000);
    models.push({
      provider: PROVIDER_ID,
      id,
      selector: `${PROVIDER_ID}/${id}`,
      name: `${display} (Neuralwatt)`,
      contextWindow,
      reasoning: capabilities.reasoning === true,
      input: capabilities.vision === true ? ["text", "image"] : ["text"],
      maxTokens: positiveNumber(limits.max_output_tokens, Math.min(16_384, contextWindow), contextWindow),
      cost: {
        input: nonNegativeNumber(pricing.input_per_million),
        output: nonNegativeNumber(pricing.output_per_million),
        cacheRead: nonNegativeNumber(pricing.cached_input_per_million),
        cacheWrite: nonNegativeNumber(pricing.cache_write_per_million),
      },
    });
  }
  return models;
}

function renderModelsYaml(models: NeuralwattModel[]): string {
  const lines = [
    `${GENERATED_CONFIG_MARKER} Contains no credential; the key is supplied through an encrypted runtime vault.`,
    "providers:",
    "  neuralwatt:",
    `    baseUrl: ${JSON.stringify(BASE_URL)}`,
    `    apiKey: ${JSON.stringify(SECRET_ENV)}`,
    "    api: openai-completions",
    "    auth: apiKey",
    "    authHeader: true",
    "    models:",
  ];
  for (const model of models) {
    const contextWindow = positiveNumber(model.contextWindow, 131_072, 2_000_000);
    lines.push(
      `      - id: ${JSON.stringify(model.id)}`,
      `        name: ${JSON.stringify(model.name ?? model.id)}`,
      "        api: openai-completions",
      `        reasoning: ${model.reasoning === true}`,
      `        input: [${(model.input ?? ["text"]).map((value) => JSON.stringify(value)).join(", ")}]`,
      `        contextWindow: ${contextWindow}`,
      `        maxTokens: ${model.maxTokens}`,
      "        cost:",
      `          input: ${model.cost.input}`,
      `          output: ${model.cost.output}`,
      `          cacheRead: ${model.cost.cacheRead}`,
      `          cacheWrite: ${model.cost.cacheWrite}`,
    );
  }
  return `${lines.join("\n")}\n`;
}

function missingCredentialError(): string {
  return "Neuralwatt models are configured, but no API key is available. Axiomux refused to start the provider runtime so the literal NEURALWATT_API_KEY placeholder can never be used as a credential. Run `npm run dev -- login neuralwatt` to restore it.";
}

function unreadableCredentialError(): string {
  return "The configured Neuralwatt credential could not be decrypted for this OS user. Axiomux refused to start the provider runtime. Run `npm run dev -- login neuralwatt` to replace the credential.";
}

function objectValue(value: unknown): Record<string, unknown> {
  return value && typeof value === "object" && !Array.isArray(value) ? (value as Record<string, unknown>) : {};
}

function positiveNumber(value: unknown, fallback: number, maximum: number): number {
  return typeof value === "number" && Number.isFinite(value) && value > 0 ? Math.min(Math.round(value), maximum) : fallback;
}

function nonNegativeNumber(value: unknown): number {
  return typeof value === "number" && Number.isFinite(value) && value >= 0 ? value : 0;
}

function readBoundedModelConfig(path: string): string {
  const metadata = lstatSync(path);
  if (!metadata.isFile() || metadata.isSymbolicLink() || metadata.nlink > 1 || metadata.size > MAX_MODEL_CONFIG_BYTES) {
    throw new Error("Neuralwatt model catalog is not a bounded regular file");
  }
  return readFileSync(path, "utf8");
}
